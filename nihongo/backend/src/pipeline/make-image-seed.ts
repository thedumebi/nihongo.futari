/* eslint-disable no-console */
import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

import { IMAGE_ALIASES } from './data/image-aliases.js'
import { listKeys } from './lib/bucket.js'

/**
 * Write the seed that attaches vocabulary illustrations to their cards.
 *
 * Production never runs a pipeline script, so `import:images` — which talks to
 * the database directly — is a local convenience only. What actually ships is a
 * seed, and this generates it.
 *
 * The list of ent_seqs has to be literal: it is the answer to "which drawings
 * exist", which lives in the bucket and cannot be derived in SQL. Everything
 * else IS derived — the URL is built from the ent_seq in the query, so moving
 * the bucket stays an env change rather than an edit to thousands of lines.
 *
 * A NEW numbered file every time, never an edit to the last one: `seed_history`
 * records seeds by filename with no content hash, so a seed that has already
 * run in production will never run again however much it changes. Emitting the
 * complete current list rather than only what is new is therefore deliberate —
 * re-attaching a drawing a card already has is a no-op, so a superset is safe
 * and cannot leave a gap if a batch is ever missed.
 *
 * Two mappings are emitted. The first attaches each word to its OWN drawing.
 * The second attaches a word to ANOTHER word's drawing, for pairs that mean the
 * same thing — 書物 can honestly use 本's book, and drawing a second book would
 * add a file without adding information. Those pairs are curated in
 * `data/image-aliases.ts` rather than derived, because the obvious derivation
 * (identical English gloss) is wrong often enough to matter: it pairs 書斎, a
 * study ROOM, with 勉強, studying.
 *
 *   pnpm -C nihongo/backend seed:images
 */

const SEEDS = path.resolve(process.cwd(), 'src/db/seeds')

async function main() {
  const stored = await listKeys('images/vocab/')
  const entSeqs = [...stored.keys()]
    .map(key => Number.parseInt(path.basename(key, '.svg'), 10))
    .filter(n => Number.isFinite(n))
    .sort((a, b) => a - b)

  if (entSeqs.length === 0)
    throw new Error('No vocabulary illustrations in the bucket — nothing to seed.')

  const existing = (await readdir(SEEDS)).filter(f => f.endsWith('.sql')).sort()
  const last = existing.at(-1)
  const next = String(Number.parseInt(last?.slice(0, 3) ?? '0', 10) + 1).padStart(3, '0')
  const name = `${next}-vocab-illustrations.sql`

  // Twelve to a line: short enough to read in a diff, long enough that several
  // thousand ids do not become several thousand lines.
  const rows: string[] = []
  for (let i = 0; i < entSeqs.length; i += 12)
    rows.push(`    ${entSeqs.slice(i, i + 12).join(', ')}`)

  // Only aliases whose TARGET was actually drawn. A curated pair pointing at a
  // picture that does not exist would give the borrower a 404 rather than the
  // owner's drawing, which is worse than leaving it blank.
  const drawn = new Set(entSeqs)
  const aliases = Object.entries(IMAGE_ALIASES)
    .map(([from, to]) => [Number(from), to] as const)
    .filter(([, to]) => drawn.has(to))
    .sort((a, b) => a[0] - b[0])

  const sql = `-- Vocabulary illustrations: attach the hand-drawn SVG to every word that has one.
--
-- Generated by \`pnpm -C nihongo/backend seed:images\` from the bucket listing.
-- ${entSeqs.length} drawings exist under \`images/vocab/<ent_seq>.svg\`, keyed by JMdict
-- ent_seq exactly as the audio is.
--
-- The ent_seq list is literal because it cannot be derived in SQL: it is the
-- answer to "which drawings exist", which lives in the bucket. The URL is built
-- from the ent_seq below, so moving the bucket stays an env change.
--
-- \`assets\` is MERGED, not replaced: audio already lives in that column and
-- overwriting it would silence every card this touches.
--
-- Touches \`assets\` on vocabulary prompts and nothing else -- no accounts, no
-- srs_cards, no review logs. Safe on a live database, and safe to re-run: the
-- final predicate makes a second run a no-op.
UPDATE exercise_prompts p
SET assets = p.assets || jsonb_build_object('image', '/images/vocab/' || w.ent_seq || '.svg'),
    updated_at = now()
FROM study_item_facets f
JOIN study_items si ON si.id = f.study_item_id
JOIN words w ON w.id = si.word_id
WHERE p.facet_id = f.id
  AND w.ent_seq IN (
${rows.join(',\n')}
  )
  -- Only where it would actually change something.
  AND coalesce(p.assets ->> 'image', '') <> '/images/vocab/' || w.ent_seq || '.svg';
`

  const aliasSql = aliases.length === 0
    ? ''
    : `
-- ---------------------------------------------------------------------------
-- Words that borrow another word's drawing.
--
-- ${aliases.length} pairs that mean the same thing, so one picture teaches both and a
-- second drawing would add a file without adding information.
--
-- Curated in \`pipeline/data/image-aliases.ts\`, never derived. Matching words by
-- shared English gloss looks obvious and is wrong often enough to be dangerous:
-- it pairs 書斎 (a study ROOM) with 勉強 (studying), 岸 (a riverbank) with 銀行,
-- and 博士 (a PhD) with 医師 (a physician).
--
-- Same merge and same re-run guard as above.
UPDATE exercise_prompts p
SET assets = p.assets || jsonb_build_object('image', '/images/vocab/' || a.target || '.svg'),
    updated_at = now()
FROM study_item_facets f
JOIN study_items si ON si.id = f.study_item_id
JOIN words w ON w.id = si.word_id
JOIN (VALUES
${aliases.map(([from, to]) => `    (${from}, ${to})`).join(',\n')}
) AS a(source, target) ON a.source = w.ent_seq
WHERE p.facet_id = f.id
  AND coalesce(p.assets ->> 'image', '') <> '/images/vocab/' || a.target || '.svg';
`

  await writeFile(path.join(SEEDS, name), sql + aliasSql)
  console.log(`Wrote ${name} — ${entSeqs.length} illustrations, ${aliases.length} aliases`)
}

main().catch((err) => {
  console.error('Seed generation failed:', err)
  process.exitCode = 1
})
