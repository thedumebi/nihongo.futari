/* eslint-disable no-console */
import { connection } from '@nihongo/shared/db'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

import { LEVEL_RANK } from '../lib/reading-checks.js'
import { checkReadings } from './check-readings.js'
import { READINGS } from './data/readings/index.js'

/**
 * Write the next numbered seed carrying every speech no earlier seed has.
 *
 *   pnpm -C nihongo/backend seed:readings
 *
 * How speeches reach production. A deploy runs pending seeds and never a
 * pipeline script, so this is what ships them. Each speech arrives UNPUBLISHED
 * with a pending row in the admin review queue; approving it there publishes
 * it, and nothing else does.
 *
 * Refuses to write anything if `check:readings` fails. The ruby is computed
 * here and written into the seed, so the deploy needs no dictionary to apply it.
 *
 * A NEW file every time, never an edit: `seed_history` records seeds by
 * filename, so an applied seed never runs again however much it changes. A
 * speech already in an earlier seed is left out — to revise one after it has
 * shipped, give the new version a new code.
 *
 * Idempotent as well, should it ever be re-applied: every insert is ON CONFLICT
 * DO NOTHING or guarded by NOT EXISTS, so an existing speech, its lines and its
 * review decision are never touched.
 */

const SEEDS = path.resolve(process.cwd(), 'src/db/seeds')
const LANGUAGE = 'lang-ja'

/** A SQL string literal. */
const q = (value: string) => `'${value.replace(/'/g, '\'\'')}'`

async function main(): Promise<void> {
  const files = (await readdir(SEEDS)).filter(f => /^\d{3}-/.test(f)).sort()
  const shipped = (await Promise.all(files.filter(f => f.endsWith('.sql')).map(f => readFile(path.join(SEEDS, f), 'utf8')))).join('\n')
  const fresh = READINGS.filter(r => !shipped.includes(q(`rdg-ja-${r.code}`)))
  if (fresh.length === 0) {
    console.log('Every speech is already in a seed. Nothing to write.')
    return
  }

  const { problems, furigana } = await checkReadings(fresh)
  if (problems.length > 0) {
    for (const p of problems) console.error(`✗ ${p}`)
    throw new Error(`${problems.length} problem(s) — fix them before seeding`)
  }

  const statements: string[] = []
  for (const r of fresh) {
    const id = `rdg-ja-${r.code}`
    const sortIndex = READINGS.indexOf(r)

    statements.push(`-- ${r.level} · ${r.code} · ${r.titleEn}
INSERT INTO readings (id, language_id, level_id, code, title, title_en, published, sort_index)
SELECT ${q(id)}, ${q(LANGUAGE)}, ll.id, ${q(r.code)}, ${q(r.title)}, ${q(r.titleEn)}, false, ${sortIndex}
FROM language_levels ll
WHERE ll.language_id = ${q(LANGUAGE)} AND ll.code = ${q(r.level)}
ON CONFLICT (language_id, code) DO NOTHING;`)

    const values: string[] = []
    let index = 0
    for (const [stanza, lines] of r.stanzas.entries()) {
      for (const line of lines) {
        const ruby = furigana.get(`${r.code}:${index}`)
        values.push(`  (${q(`${id}-l${index}`)}, ${q(id)}, ${index}, ${stanza}, ${q(line.t)}, ${q(line.r)}, ${ruby ? `${q(JSON.stringify(ruby))}::jsonb` : 'NULL'}, ${q(line.e)})`)
        index++
      }
    }
    // Only if the speech row above is ours: a code already taken by another id
    // must not have lines attached to it.
    statements.push(`INSERT INTO reading_lines (id, reading_id, index, stanza, text, reading_kana, furigana, translation)
SELECT v.* FROM (VALUES
${values.join(',\n')}
) AS v(id, reading_id, index, stanza, text, reading_kana, furigana, translation)
WHERE EXISTS (SELECT 1 FROM readings WHERE id = ${q(id)})
ON CONFLICT (reading_id, index) DO NOTHING;`)

    // Priority is the level, so the queue lists N5 first and works upward.
    statements.push(`INSERT INTO content_review_queue (id, language_id, target_table, target_id, change_type, proposed, origin, priority, status)
SELECT ${q(`crq-${id}`)}, ${q(LANGUAGE)}, 'readings', ${q(id)}, 'create', ${q(JSON.stringify({ code: r.code, level: r.level }))}::jsonb, 'ai', ${LEVEL_RANK[r.level]}, 'pending'
WHERE EXISTS (SELECT 1 FROM readings WHERE id = ${q(id)} AND NOT published)
  AND NOT EXISTS (SELECT 1 FROM content_review_queue WHERE target_table = 'readings' AND target_id = ${q(id)})
ON CONFLICT DO NOTHING;`)
  }

  const last = files.at(-1)
  const next = String(Number.parseInt(last?.slice(0, 3) ?? '0', 10) + 1).padStart(3, '0')
  const name = `${next}-readings.sql`
  const header = `-- Read-aloud speeches: ${fresh.length} of them, ${fresh.map(r => r.level).filter((l, i, a) => a.indexOf(l) === i).join(', ')}.
--
-- Generated by \`pnpm -C nihongo/backend seed:readings\` from
-- backend/src/pipeline/data/readings. Do not edit: change the data and generate
-- a new seed.
--
-- Every speech arrives UNPUBLISHED with a pending row in the admin review queue.
-- Approving it there is the only thing that publishes it.
--
-- Idempotent: nothing here overwrites an existing speech, its lines, or a
-- review decision already made.

`
  await writeFile(path.join(SEEDS, name), `${header}${statements.join('\n\n')}\n`)
  console.log(`Wrote src/db/seeds/${name}: ${fresh.length} speeches, ${fresh.reduce((n, r) => n + r.stanzas.flat().length, 0)} lines`)
}

main()
  .catch((err) => {
    console.error('Failed:', err instanceof Error ? err.message : err)
    process.exitCode = 1
  })
  .finally(async () => {
    await connection.end()
  })
