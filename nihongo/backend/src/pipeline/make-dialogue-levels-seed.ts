import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

import { DIALOGUE_LEVELS } from './data/dialogues/levels.js'

/**
 * Write the next numbered seed that sets each conversation's level.
 *
 *   pnpm -C nihongo/backend seed:dialogue-levels
 *
 * Production never runs the importer, so the levels reach it as a seed: the
 * conversation's level and its study item's, by code. Idempotent — an UPDATE
 * that only changes rows not already at their level.
 */
const SEEDS = path.resolve(process.cwd(), 'src/db/seeds')
const q = (value: string) => `'${value.replace(/'/g, "''")}'`

async function main(): Promise<void> {
  const entries = Object.entries(DIALOGUE_LEVELS)
  const values = entries.map(([code, level]) => `  (${q(code)}, ${q(`lvl-ja-${level.toLowerCase()}`)})`).join(',\n')
  const files = (await readdir(SEEDS)).filter(f => /^\d{3}-/.test(f)).sort()
  const next = String(Number.parseInt(files.at(-1)?.slice(0, 3) ?? '0', 10) + 1).padStart(3, '0')
  const name = `${next}-dialogue-levels.sql`
  const counts = entries.reduce<Record<string, number>>((n, [, l]) => ({ ...n, [l]: (n[l] ?? 0) + 1 }), {})

  const body = `-- The JLPT level of every conversation — ${Object.entries(counts).map(([l, n]) => `${n} ${l}`).join(', ')}.
--
-- Generated by \`pnpm -C nihongo/backend seed:dialogue-levels\` from
-- backend/src/pipeline/data/dialogues/levels.ts, which the Sonnet → Opus →
-- Sonnet → Fable pipeline filled in. Every conversation used to be imported as
-- N5; the level is the hardest grammar and vocabulary a learner must produce
-- or understand in it. The conversation's study item follows.
--
-- Idempotent: only rows not already at their level change.

UPDATE dialogues d SET level_id = v.level_id, updated_at = now()
FROM (VALUES
${values}
) AS v(code, level_id)
WHERE d.language_id = 'lang-ja' AND d.code = v.code AND d.level_id IS DISTINCT FROM v.level_id;

UPDATE study_items si SET level_id = d.level_id, updated_at = now()
FROM dialogues d
WHERE si.dialogue_id = d.id AND d.language_id = 'lang-ja' AND si.level_id IS DISTINCT FROM d.level_id;
`
  await writeFile(path.join(SEEDS, name), body)
  console.log(`Wrote src/db/seeds/${name}: ${entries.length} conversations`)
}

void main()
