/* eslint-disable no-console */
import db, { connection } from '@nihongo/shared/db'
import { sql } from 'drizzle-orm'
import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

import { sentenceAudioPath, voiceForClip, wordAudioPath } from '../lib/audio-key.js'
import { listKeys } from './lib/bucket.js'

/**
 * Tell production which sentence and word recordings exist.
 *
 * Run after `audio:sentences` / `audio:words`. For every published sentence
 * and word whose clip (named for its text and voice) is in the bucket, the seed
 * records that text and voice on the row. The app plays a clip only while the
 * row's text still matches what the clip says, so a reworded item goes quiet
 * until it is recorded again and this is re-run, instead of playing the old
 * words.
 *
 * Each update also requires the text to be unchanged, so a seed generated
 * before a rewording can never mark the new text as recorded.
 *
 *   pnpm -C nihongo/backend seed:clip-audio
 */

const SEEDS = path.resolve(process.cwd(), 'src/db/seeds')

const lit = (s: string) => `'${s.replaceAll('\'', '\'\'')}'`

async function main() {
  const [sentenceClips, wordClips] = await Promise.all([listKeys('audio/sentences/'), listKeys('audio/words/')])
  const sentences = (await db.execute<{ id: string, text: string }>(sql`select id, text from sentences where published order by id`)).rows
  const words = (await db.execute<{ ent_seq: number, reading: string }>(sql`select ent_seq, primary_reading as reading from words where published and ent_seq is not null order by ent_seq`)).rows

  const sentenceRows: string[] = []
  for (const s of sentences) {
    const voice = voiceForClip(s.id)
    if (sentenceClips.has(sentenceAudioPath(s.text, voice).slice(1)))
      sentenceRows.push(`  (${lit(s.id)}, ${lit(s.text)}, ${lit(voice)})`)
  }
  const wordRows: string[] = []
  for (const w of words) {
    const voice = voiceForClip(w.ent_seq)
    if (wordClips.has(wordAudioPath(w.reading, voice).slice(1)))
      wordRows.push(`  (${w.ent_seq}, ${lit(w.reading)}, ${lit(voice)})`)
  }
  console.log(`sentences: ${sentenceRows.length} of ${sentences.length} recorded`)
  console.log(`words: ${wordRows.length} of ${words.length} recorded`)
  if (sentenceRows.length + wordRows.length === 0)
    throw new Error('No recordings in the bucket: run audio:sentences / audio:words first.')

  const existing = (await readdir(SEEDS)).filter(f => /^\d{3}-.*\.(?:sql|seed\.ts)$/.test(f)).sort()
  const next = String(Number.parseInt(existing.at(-1)?.slice(0, 3) ?? '0', 10) + 1).padStart(3, '0')
  const name = `${next}-clip-audio.sql`

  const body = [
    `-- Which sentence and word recordings exist: ${sentenceRows.length} sentences, ${wordRows.length} words.`,
    '--',
    '-- Generated by `pnpm -C nihongo/backend seed:clip-audio` after an audio run. Do not',
    '-- edit: regenerate. A row is marked only if its text is still what was',
    '-- recorded, so re-running it, or running it late, changes nothing wrongly.',
    '',
    ...(sentenceRows.length
      ? [
          'UPDATE sentences s SET audio_text = v.text, audio_voice = v.voice',
          'FROM (VALUES',
          sentenceRows.join(',\n'),
          ') AS v(id, text, voice)',
          'WHERE s.id = v.id AND s.text = v.text',
          '  AND (s.audio_text IS DISTINCT FROM v.text OR s.audio_voice IS DISTINCT FROM v.voice);',
          ''
        ]
      : []),
    ...(wordRows.length
      ? [
          'UPDATE words w SET audio_text = v.reading, audio_voice = v.voice',
          'FROM (VALUES',
          wordRows.join(',\n'),
          ') AS v(ent_seq, reading, voice)',
          'WHERE w.ent_seq = v.ent_seq AND w.primary_reading = v.reading',
          '  AND (w.audio_text IS DISTINCT FROM v.reading OR w.audio_voice IS DISTINCT FROM v.voice);',
          ''
        ]
      : [])
  ].join('\n')
  await writeFile(path.join(SEEDS, name), body)
  console.log(`Wrote ${name}`)
}

main()
  .catch((err) => {
    console.error('Seed generation failed:', err)
    process.exitCode = 1
  })
  .finally(async () => {
    await connection.end()
  })
