/* eslint-disable no-console */
import db from '@nihongo/shared/db'
import { lookAlikes, parseIds } from '@nihongo/shared/lib'
import { sql } from 'drizzle-orm'
import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

/**
 * Write the next numbered seed of look-alike kanji.
 *
 *   pnpm -C nihongo/backend seed:confusables
 *
 * Derived, not authored: two kanji look alike when they share a part in the
 * same layout (待 持 時 all ⿰ around 寺), weighted towards distinctive parts —
 * `lookAlikes` in the shared lib. Only kanji with a JLPT level take part, so
 * the pairs are ones a learner will actually meet. Feeds the ghost boss and
 * any multiple choice that wants a convincing wrong answer.
 *
 * Idempotent: keyed on (kanji, confusable, reason), nothing existing changes.
 */
const SEEDS = path.resolve(process.cwd(), 'src/db/seeds')
const q = (value: string) => `'${value.replace(/'/g, "''")}'`

async function main(): Promise<void> {
  const rows = await db.execute<{ character: string, ids: string | null }>(sql`
    select k.character, max(kc.ids_expression) as ids
    from kanji k
    join languages l on l.id = k.language_id and l.code = 'ja'
    join kanji_components kc on kc.parent_kanji_id = k.id
    where k.level_id is not null
    group by k.character
  `)
  const entries = rows.rows.flatMap((r) => {
    const shape = parseIds(r.ids)
    return shape ? [{ character: r.character, shape }] : []
  })
  const pairs = lookAlikes(entries)

  const files = (await readdir(SEEDS)).filter(f => /^\d{3}-/.test(f)).sort()
  const next = String(Number.parseInt(files.at(-1)?.slice(0, 3) ?? '0', 10) + 1).padStart(3, '0')
  const name = `${next}-kanji-confusables.sql`
  const values = pairs.map(p => `  (${q(p.character)}, ${q(p.confusable)}, ${p.score})`).join(',\n')

  const body = `-- Look-alike kanji: ${pairs.length} pairs over ${entries.length} levelled kanji.
--
-- Generated by \`pnpm -C nihongo/backend seed:confusables\`
-- (backend/src/pipeline/derive-confusables.ts). Two kanji look alike when they
-- share a part in the same layout, weighted towards distinctive parts; each
-- keeps its three closest. Derived from the IDS decomposition already in
-- kanji_components — nothing here is written by hand or by a model.
--
-- Idempotent: keyed on (kanji, confusable, reason).

INSERT INTO kanji_confusables (id, kanji_id, confusable_id, reason, score)
SELECT gen_random_uuid()::text, a.id, b.id, 'similar-shape', v.score
FROM (VALUES
${values}
) AS v(kanji, confusable, score)
JOIN kanji a ON a.language_id = 'lang-ja' AND a.character = v.kanji
JOIN kanji b ON b.language_id = 'lang-ja' AND b.character = v.confusable
ON CONFLICT (kanji_id, confusable_id, reason) DO NOTHING;
`
  await writeFile(path.join(SEEDS, name), body)
  console.log(`Wrote src/db/seeds/${name}: ${pairs.length} pairs over ${entries.length} kanji`)
  process.exit(0)
}

void main()
