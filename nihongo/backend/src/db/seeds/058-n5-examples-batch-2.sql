-- Same shape as 056 and the same rule: every sentence passed `check:examples`
-- before this file existed.
--
-- Two topics that should have been in this batch are NOT here, because the
-- tokeniser cannot read their own pattern:
--
--   〜てもいい          もいい cuts as も | い | い
--   〜なければなりません  なければ cuts as な | け | れ | ば
--
-- Neither is a word the dictionary holds — they are grammar, assembled from
-- pieces — and いい is deliberately blocked besides, because 飯 "cooked rice"
-- is also read いい and would claim the spelling. A lesson whose example
-- sentences shred the very pattern they teach is worse than no lesson, so they
-- wait for the tokeniser to learn about grammar patterns. i-adjective and
-- na-adjective take their place here.
--
-- 〜が (but) is written as ますが rather than ですが throughout: です has no
-- dictionary entry and always splits into で + す, which passes unnoticed at the
-- end of a sentence and reads as shredded kana in the middle of one.
--
-- Additive, idempotent, safe on a live database.

